def read_kyuura_cards(kyuura: Path) -> dict:
    """固定したコミットの data/cards.json を読む（作業ツリーは見ない）。"""
    result = subprocess.run(
        ["git", "-C", str(kyuura), "show", f"{KYUURA_COMMIT}:{KYUURA_PATH}"],
        check=True,
        capture_output=True,
    )
    return json.loads(result.stdout.decode("utf-8"))


